-- 1. Create table for website project enquiries
create table if not exists public.contact_submissions (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  service text not null,
  project_details text not null,
  source text default 'Arche Creative Studios Contact Form',
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Enable Row Level Security (RLS)
alter table public.contact_submissions enable row level security;

-- 3. Drop existing policies if they exist (for idempotent runs)
drop policy if exists "Allow public anonymous inserts" on public.contact_submissions;
drop policy if exists "Allow read for service role and authenticated" on public.contact_submissions;

-- 4. Policy: Allow any website visitor (anonymous, authenticated, service_role) to submit an enquiry
create policy "Allow public anonymous inserts"
on public.contact_submissions
for insert
to anon, authenticated, service_role
with check (true);

-- 5. Policy: Allow dashboard / service_role to read and manage all inquiries
create policy "Allow read for service role and authenticated"
on public.contact_submissions
for select
to service_role, authenticated
using (true);

